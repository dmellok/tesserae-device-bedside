# Pack the dawn-chorus clips (assets/birds/<species>_<n>.wav, made by
# tools/make_bird_clips.py) into one 8-bit mu-law blob for flash, plus
# include/birds_index.h with each clip's offset and length and src/birds_data.S
# to embed it. Runs before every PlatformIO build and skips the (pure-Python)
# encode when nothing changed.
import os, json, wave, struct, hashlib
Import("env")  # noqa: F821
root = env.subst("$PROJECT_DIR")  # noqa: F821
adir = os.path.join(root, "assets", "birds")
out_bin = os.path.join(adir, "birds.ulaw")
out_hdr = os.path.join(root, "include", "birds_index.h")
out_asm = os.path.join(root, "src", "birds_data.S")


def ulaw(s):                      # G.711 mu-law encode of one int16 sample
    BIAS, CLIP = 0x84, 32635
    sign = 0x80 if s < 0 else 0
    if s < 0:
        s = -s
    if s > CLIP:
        s = CLIP
    s += BIAS
    exp, mask = 7, 0x4000
    while exp > 0 and not (s & mask):
        exp -= 1
        mask >>= 1
    return (~(sign | (exp << 4) | ((s >> (exp + 3)) & 0x0F))) & 0xFF


def build():
    cfg = json.load(open(os.path.join(adir, "clips.json")))
    table = bytes(ulaw(v - 32768) for v in range(65536))
    blob, rows = bytearray(), []
    for si, sp in enumerate(cfg["species"]):
        for n in range(len(cfg["species"][sp]["clips"])):
            w = wave.open(os.path.join(adir, "%s_%d.wav" % (sp, n)))
            assert w.getframerate() == 22050 and w.getnchannels() == 1 and w.getsampwidth() == 2
            pcm = w.readframes(w.getnframes())
            off = len(blob)
            blob += bytes(table[v + 32768] for v in struct.unpack("<%dh" % (len(pcm) // 2), pcm))
            rows.append((si, off, len(blob) - off))
    open(out_bin, "wb").write(blob)
    hdr = ["/* Generated by scripts/build_birds.py from assets/birds/clips.json. Do not edit. */",
           "#pragma once", "#include <stdint.h>",
           "typedef struct { uint8_t species; uint32_t off, len; } bird_clip_t;",
           "#define BIRD_CLIPS %d" % len(rows),
           "static const bird_clip_t BIRD_CLIP[BIRD_CLIPS] = {"]
    hdr += ["    { %d, %d, %d }," % r for r in rows] + ["};", ""]
    open(out_hdr, "w").write("\n".join(hdr))
    open(out_asm, "w").write(
        "/* The dawn-chorus clips (assets/birds/birds.ulaw, 8-bit mu-law, 22.05 kHz). */\n"
        ".section .rodata\n.balign 4\n.global bird_data\nbird_data:\n"
        ".incbin \"assets/birds/birds.ulaw\"\n.global bird_data_end\nbird_data_end:\n"
        "/* sha1 %s */\n" % hashlib.sha1(blob).hexdigest())
    print("birds: packed %d clips, %d bytes" % (len(rows), len(blob)))


srcs = [os.path.join(adir, "clips.json"), os.path.join(root, "scripts", "build_birds.py")]
srcs += [os.path.join(adir, f) for f in os.listdir(adir) if f.endswith(".wav")]
outs = [out_bin, out_hdr, out_asm]
if not all(os.path.exists(o) for o in outs) or min(map(os.path.getmtime, outs)) < max(map(os.path.getmtime, srcs)):
    build()
