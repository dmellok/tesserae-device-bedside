/* ---- the alarm clock and the dawn chorus ------------------------------------
 * Runs on the device from the server's clock (Date header + its UTC offset), so
 * the chorus still comes if Home Assistant is down. Before each alarm the wake
 * window (the alarm's "wake up early", else 10 min) builds the chorus from one
 * distant bird to a full one while the sleep sound fades; at the alarm time the
 * panel rings with the chorus at full. Knob press stops; any key or a turn
 * snoozes for 9 min; it gives up after 30 min. A "Once" alarm (no days)
 * switches itself off after it has rung. */
#define SNOOZE_MS     ((uint32_t)S.snooze_min * 60u * 1000u)
#define RING_MAX_MS   (30u * 60u * 1000u)
static uint32_t s_ring_ms, s_snooze_until_ms;
static int      s_ring_alarm = -1;
static int64_t  s_fired_min = -10;

static bool clock_now(int *wday, int *sec, int64_t *minute)
{
    int64_t e = utc_now();
    if (!e) return false;
    alarm_split_time(e + tz_offset_at(e), wday, sec, minute);
    return true;
}

/* The next enabled alarm and the seconds until it; without a clock yet, the
 * first enabled alarm and -1. */
static bool next_alarm(int *idx, int32_t *delta_s)
{
    int wday, sec; int64_t minute;
    *idx = -1; *delta_s = -1;
    if (!clock_now(&wday, &sec, &minute)) {
        for (int i = 0; i < s_nalarms; i++) if (s_alarms[i].on) { *idx = i; return true; }
        return false;
    }
    *idx = alarm_next(s_alarms, s_nalarms, wday * 86400 + sec, false, delta_s);
    return *idx >= 0;
}

static void ring(int i)
{
    s_ring_alarm = i; s_ring_ms = now_ms(); s_snooze_until_ms = 0; s_preview_len_ms = 0;
    if (i >= 0 && i < s_nalarms) { S.alarm_h = s_alarms[i].h; S.alarm_m = s_alarms[i].m; }
    S.phase = PHASE_RINGING; S.rain_on = false; S.lights_on = true;
    publish("event", "alarm_ringing");
    s_mode = M_HOME; s_depth = 0; mark_screen();
}

static void snooze(void)
{
    S.phase = PHASE_IDLE; s_snooze_until_ms = now_ms() + SNOOZE_MS;
    publish("event", "alarm_snoozed %d min", S.snooze_min); go_home();
}

static void stop_alarm(void)
{
    S.phase = PHASE_IDLE; s_snooze_until_ms = 0;
    int i = s_ring_alarm; s_ring_alarm = -1;
    if (i >= 0 && i < s_nalarms) {
        if (alarm_is_once(&s_alarms[i])) { s_alarms[i].on = false; alarms_save(); sync_alarm_summary(); }
    }
    publish("event", "alarm_stopped"); go_home();
}

static void chorus_preview(int seconds)
{
    if (seconds <= 0) { s_preview_len_ms = 0; publish("event", "chorus_preview_stop"); return; }
    s_preview_start_ms = now_ms(); s_preview_len_ms = (uint32_t)seconds * 1000u;
    publish("event", "chorus_preview %d s", seconds);
}

void local_alarm_tick(bool *changed)
{
    uint32_t t = now_ms();
    {   /* auto night: switch at the window's edges only, so a manual change holds until the next one */
        static int last_in = -1;
        int wd, sc; int64_t mn;
        if (S.auto_night && clock_now(&wd, &sc, &mn)) {
            int in = alarm_auto_night_in(S.auto_night, sc / 60) ? 1 : 0;
            if (in != last_in) {
                last_in = in;
                if ((bool)in != S.night) {
                    S.night = in; inputs_set_night(S.night); config_set_lights(inputs_backlight(), S.night); config_save();
                    publish("config/night", S.night ? "on" : "off");
                    rebuild(); R_SBMID(); if (changed) *changed = true;
                }
            }
        } else last_in = -1;
    }
    float c = 0;
    if (s_preview_len_ms) {                         /* preview: build, then 20 s at full */
        uint32_t el = t - s_preview_start_ms;
        if (el < s_preview_len_ms) c = 0.05f + 0.95f * (float)el / (float)s_preview_len_ms;
        else if (el < s_preview_len_ms + 20000u) c = 1.0f;
        else { s_preview_len_ms = 0; if (changed) *changed = true; rebuild(); }
    }
    if (S.phase == PHASE_RINGING) {
        c = 1.0f;
        if (t - s_ring_ms > RING_MAX_MS) { stop_alarm(); if (changed) *changed = true; }
        S.chorus = c; return;
    }
    if (s_snooze_until_ms) {
        if ((int32_t)(t - s_snooze_until_ms) >= 0) { ring(s_ring_alarm); if (changed) *changed = true; S.chorus = 1.0f; return; }
        S.chorus = c; return;
    }
    int wday, sec; int64_t minute;
    if (!clock_now(&wday, &sec, &minute)) { S.chorus = c; return; }
    int32_t best_delta;
    int best = alarm_next(s_alarms, s_nalarms, wday * 86400 + sec, true, &best_delta);
    if (best >= 0 && best_delta <= 0 && minute - s_fired_min > 1) {
        s_fired_min = minute;
        ring(best); if (changed) *changed = true; S.chorus = 1.0f; return;
    }
    if (best >= 0 && best_delta > 0) {
        int win = alarm_window_s(&s_alarms[best]);
        if (best_delta <= win) {
            float w = alarm_chorus_level(best_delta, win);
            if (w > c) c = w;
            if (S.phase == PHASE_IDLE) {
                S.phase = PHASE_PREWAKE; S.lights_on = true; S.bright = 30;
                publish("event", "prewake %02d:%02d", s_alarms[best].h, s_alarms[best].m);
                rebuild(); if (s_mode == M_HOME) R_SBMID(); if (changed) *changed = true;
            }
            S.chorus = c; return;
        }
    }
    if (S.phase == PHASE_PREWAKE) S.phase = PHASE_IDLE;   /* the alarm was moved or switched off */
    S.chorus = c;
}

/* Speed: detents arriving close together count for more. A slow click moves
 * one step; a quick flick takes steps of 3x / 6x. Values only: in lists and
 * choices every detent is exactly one row. */
static uint32_t s_last_turn_ms;
static int accel_for(int d)
{
    uint32_t now = now_ms(), dt = now - s_last_turn_ms;
    s_last_turn_ms = now;
    int ad = d < 0 ? -d : d;
    if (ad >= 4 || dt < 60)  return 6;
    if (ad >= 2 || dt < 140) return 3;
    return 1;
}

/* Knob turn; d is the signed number of detents since the last call. */
bool local_turn(int d)
{
    if (!d) return true;
    if (S.phase == PHASE_RINGING) { snooze(); return true; }
    int acc = accel_for(d);
    switch (s_mode) {
    case M_HOME: volume(d > 0 ? 1 : -1); return true;
    case M_LIST: {
        int *sel = &s_stack[s_depth - 1].sel, n = node_rows(s_stack[s_depth - 1].node, s_rows), old = *sel;
        *sel = clampi(*sel + d, 0, n - 1);          /* one detent, one row: no speed-up in lists */
        if (*sel != old) mark_rows(old, *sel);
        return true; }
    case M_CHOICE: {
        const char *const *o; int n = choice_opts(s_edit, &o) + 1, old = s_csel;
        s_csel = clampi(s_csel + d, 0, n - 1);
        if (s_csel != old) mark_rows(old, s_csel);
        return true; }
    case M_VALUE: value_step(s_edit, d, acc); mark_value(); return true;
    }
    return true;
}

/* The centre button: choose. */
bool local_press(void)
{
    if (S.phase == PHASE_RINGING) { stop_alarm(); return true; }
    switch (s_mode) {
    case M_HOME: push_node(N_ROOT); return true;
    case M_VALUE:
        if (s_edit == V_ALARM_TIME) publish_alarm(s_ai);
        s_mode = M_LIST; mark_screen(); return true;
    case M_CHOICE: {
        const char *const *o; int n = choice_opts(s_edit, &o);
        if (s_csel < n) choice_set(s_edit, s_csel);
        s_mode = M_LIST; mark_screen(); return true; }
    case M_LIST: {
        int n = node_rows(s_stack[s_depth - 1].node, s_rows), sel = s_stack[s_depth - 1].sel;
        if (sel >= n) return true;
        row_def_t r = s_rows[sel];
        switch (r.kind) {
        case K_TOGGLE: toggle_flip(&r); mark_rows(sel, sel); return true;
        case K_SUB:    if (r.id == S_ALARM_ITEM) s_ai = r.arg; if (r.id == S_KEY) s_ki = r.arg; push_node(sub_node(r.id)); return true;
        case K_VALUE:  if ((r.id == V_TIME || r.id == V_DATE) && S.auto_time) return true;
                       s_edit = r.id; snprintf(s_edit_label, sizeof s_edit_label, "%s", r.label); s_mode = M_VALUE; mark_screen(); return true;
        case K_CHOICE: if (r.id == C_DASH) tesserae_picks_fetch();     /* fresh: dashboards can be bound any time */
                       s_edit = r.id; snprintf(s_edit_label, sizeof s_edit_label, "%s", r.label); s_csel = clampi(choice_get(r.id), 0, 99); s_mode = M_CHOICE; mark_screen(); return true;
        case K_BACK:   list_back(); return true;
        case K_ACTION:
            if (r.id == A_ADD_ALARM && s_nalarms < MAX_ALARMS) {
                s_alarms[s_nalarms] = (alarm_t){ 7, 0, true, {1,1,1,1,1,0,0}, 15 };
                s_ai = s_nalarms++; publish_alarm(s_ai); sync_alarm_summary();
                s_stack[s_depth - 1].sel = s_ai;
                push_node(N_ALARM);
            } else if (r.id == A_REFRESH) {
                s_req = LREQ_REFRESH;
            } else if (r.id == A_RESTART) {
                s_req = LREQ_RESTART;
            } else if (r.id == A_WIFISETUP) {
                s_req = LREQ_SETUP;
            } else if (r.id == A_OTACHECK) {
                ota_releases_fetch(); s_rel_armed = -1; mark_screen();
            } else if (r.id == A_RELEASE) {
                if (s_rel_armed != r.arg) { s_rel_armed = r.arg; int sl = s_stack[s_depth - 1].sel; mark_rows(sl, sl); }
                else { s_rel_armed = -1; if (!ota_install(r.arg)) toast(ICON_GEAR, "Update failed", ota_error()); }
            } else if (r.id == A_PREVIEW) {
                chorus_preview(s_preview_len_ms ? 0 : 90);
                rebuild(); { int sl = s_stack[s_depth - 1].sel; mark_rows(sl, sl); }
            } else if (r.id == A_DELETE_ALARM) {
                publish("set/alarm", "%d delete", r.arg + 1);
                for (int i = r.arg; i < s_nalarms - 1; i++) s_alarms[i] = s_alarms[i + 1];
                s_nalarms--; s_ai = 0; alarms_save(); sync_alarm_summary();
                list_back();
            }
            return true;
        case K_INFO: return true;
        }
    } }
    return true;
}

