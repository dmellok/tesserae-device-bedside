#define MAX_ALARMS 4
static alarm_t s_alarms[MAX_ALARMS] = { { 6, 30, true, {1,1,1,1,1,0,0}, 15 } };
static int s_nalarms = 1, s_ai;       /* count; the alarm being edited */
