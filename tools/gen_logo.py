#!/usr/bin/env python3
"""Boot-screen logo: a 24-bit BMP -> packed 4 bpp greys (0 black .. 15 white,
high nibble = left pixel) as src/boot_logo.c.

The BMP is assets/brand/tesserae-lockup.svg (the official Tesserae Server
lockup with the SERVER badge removed) rendered at panel size, e.g. with headless
Chrome to PNG and `sips -s format bmp`. The panel has no colour: the red tile
quarter comes out as a mid grey.
    tools/gen_logo.py assets/brand/tesserae-lockup-768x200.bmp
"""
import struct, sys, os

src = sys.argv[1]
d = open(src, 'rb').read()
off = struct.unpack('<I', d[10:14])[0]
w, h = struct.unpack('<ii', d[18:26])
bpp = struct.unpack('<H', d[28:30])[0]
assert bpp in (24, 32), 'want a 24 or 32-bit BMP'
top_down = h < 0; h = abs(h)
assert w % 2 == 0
stride = (w * (bpp // 8) + 3) & ~3
out = bytearray()
for y in range(h):
    r = y if top_down else h - 1 - y
    row = d[off + r * stride: off + r * stride + w * (bpp // 8)]
    lv = []
    for x in range(w):
        b, g, rr = row[x * (bpp // 8): x * (bpp // 8) + 3]
        lum = 0.299 * rr + 0.587 * g + 0.114 * b
        lv.append(min(15, int(lum / 255 * 15 + 0.5)))
    for x in range(0, w, 2):
        out.append(lv[x] << 4 | lv[x + 1])
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
with open(os.path.join(root, 'src', 'boot_logo.c'), 'w') as f:
    f.write('/* Generated by tools/gen_logo.py from %s: the official Tesserae lockup. */\n' % os.path.basename(src))
    f.write('#include "boot_logo.h"\n\nconst uint16_t boot_logo_w = %d, boot_logo_h = %d;\n' % (w, h))
    f.write('const uint8_t boot_logo[%d] = {\n' % len(out))
    for i in range(0, len(out), 24):
        f.write('    ' + ', '.join('0x%02x' % v for v in out[i:i + 24]) + ',\n')
    f.write('};\n')
with open(os.path.join(root, 'include', 'boot_logo.h'), 'w') as f:
    f.write('/* The boot-screen logo (tools/gen_logo.py): packed 4 bpp, rows of w/2 bytes. */\n')
    f.write('#pragma once\n#include <stdint.h>\n\nextern const uint16_t boot_logo_w, boot_logo_h;\nextern const uint8_t boot_logo[];\n')
print('boot_logo: %dx%d, %d bytes' % (w, h, len(out)))
