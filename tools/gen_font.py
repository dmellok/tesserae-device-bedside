#!/usr/bin/env python3
"""Render a TrueType font into a 4-bit anti-aliased bitmap font for the device.

    gen_font.py <ttf> <px> <weight> <name> <charset> <out.c>

charset: "ascii" (32..126 plus ° as 0x7F and · as 0x80), a literal string of
characters, or "icons:<name>=<hex>,..." which maps icon-font codepoints to the
device codes 0x81.. in order and also writes include/<name>.h with ICON_* string
macros. weight is a variable-font axis value (400 regular, 500 medium ...).
Output: src/fonts/<name>.c defining `const bfont_t <name>` (see include/bfont.h).
Glyphs are packed 2 px/byte, high nibble = left pixel, 0 = no ink, 15 = full ink.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, px, weight, name, charset, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5], sys.argv[6]
font = ImageFont.truetype(ttf, px)
try:
    font.set_variation_by_axes([weight])
except Exception:
    pass
ascent, descent = font.getmetrics()
line_h = ascent + descent

icon_names = None
if charset == "ascii":
    chars = [(c, chr(c)) for c in range(32, 127)] + [(0x7F, "°"), (0x80, "·")]
elif charset.startswith("icons:"):
    icon_names = []
    chars = []
    for i, pair in enumerate(charset[6:].split(",")):
        n, hx = pair.split("=")
        chars.append((0x81 + i, chr(int(hx, 16))))
        icon_names.append((n, 0x81 + i))
else:
    chars = []
    for ch in charset:
        code = {"°": 0x7F, "·": 0x80}.get(ch, ord(ch))
        chars.append((code, ch))

bits = bytearray()
glyphs = []
for code, ch in sorted(chars):
    adv = int(round(font.getlength(ch)))
    bbox = font.getbbox(ch, anchor="la")      # relative to the pen origin at the ascender line
    if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
        glyphs.append((code, adv, 0, 0, 0, 0, len(bits)))
        continue
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="la")
    px_ = img.load()
    off = len(bits)
    for y in range(h):
        for x in range(0, w, 2):
            a = (px_[x, y] * 15 + 127) // 255
            b = (px_[x + 1, y] * 15 + 127) // 255 if x + 1 < w else 0
            bits.append((a << 4) | b)
    glyphs.append((code, adv, w, h, x0, y0, off))

with open(out, "w") as f:
    f.write(f"/* Generated by tools/gen_font.py from {ttf.split('/')[-1]} at {px} px, weight {weight}. Do not edit. */\n")
    f.write('#include "bfont.h"\n\n')
    f.write(f"static const uint8_t {name}_bits[{max(1, len(bits))}] = {{\n")
    for i in range(0, len(bits), 24):
        f.write("  " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",\n")
    if not bits:
        f.write("  0,\n")
    f.write("};\n\n")
    f.write(f"static const bglyph_t {name}_glyphs[{len(glyphs)}] = {{\n")
    for code, adv, w, h, x0, y0, off in glyphs:
        f.write(f"  {{ {code}, {adv}, {w}, {h}, {x0}, {y0}, {off} }},\n")
    f.write("};\n\n")
    f.write(f"const bfont_t {name} = {{ {name}_glyphs, {len(glyphs)}, {line_h}, {ascent}, {name}_bits }};\n")
if icon_names:
    import os
    hp = os.path.join(os.path.dirname(os.path.dirname(out)), "..", "include", "icons.h")
    hp = os.path.normpath(hp)
    with open(hp, "w") as h:
        h.write("/* Generated by tools/gen_font.py: Phosphor icon codes in the icon fonts. Do not edit. */\n#pragma once\n\n")
        for n, code in icon_names:
            h.write(f'#define ICON_{n.upper().replace("-", "_")}  "\\x{code:02x}"\n')
    print("wrote", hp)
print(f"{name}: {len(glyphs)} glyphs, {len(bits)} bytes, line {line_h} px (ascent {ascent})")
