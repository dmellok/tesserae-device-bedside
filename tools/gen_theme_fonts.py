#!/usr/bin/env python3
"""The Terminal and Blueprint themes' fonts (ui_theme.c), from their TrueType files.

    gen_theme_fonts.py            writes src/fonts/term.c and src/fonts/blue.c

Each font stands in for one of the standard theme's (src/fonts/ui30.c ...): it
has the same glyph codes, the same line height and the same baseline, so a
page laid out for the standard theme holds. The sizes of 96 px and over are
rendered at half size and drawn doubled (bfont_t.scale 2), which quarters them.

  Terminal   IBM Plex Mono, a little smaller than the standard face so that a
             fixed-width line is about as long as the proportional one was.
  Blueprint  Barlow Condensed in small capitals, as lettering on a drawing: a
             lower-case letter is its capital at four fifths of the height.
"""
import os, re
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = [("30", "ui30", 30), ("34", "ui34", 34), ("46", "ui46", 46), ("60", "ui60", 60), ("72", "ui72", 72), ("96", "ui96", 96),
         ("num180", "num180", 180), ("clock214", "clock214", 214), ("num270", "num270", 270)]
THEMES = {
    "term": dict(prefix="tm_", regular="IBMPlexMono-Medium.ttf", light="IBMPlexMono-Light.ttf", k_text=0.80, k_num=1.0, smallcaps=0),
    "blue": dict(prefix="bp_", regular="BarlowCondensed-Medium.ttf", light="BarlowCondensed-Light.ttf", k_text=1.16, k_num=1.18, smallcaps=0.8),
}

def standard(name):
    """The standard font's glyph codes, line height and ascent."""
    src = open(os.path.join(ROOT, "src", "fonts", name + ".c")).read()
    codes = [int(m) for m in re.findall(r"^  \{ (\d+),", src, re.M)]
    m = re.search(r"const bfont_t \w+ = \{ \w+, \d+, (\d+), (\d+),", src)
    return codes, int(m.group(1)), int(m.group(2))

def char_of(code):
    return {0x7F: "°", 0x80: "·"}.get(code, chr(code))

def build(theme, t):
    out = [f"/* Generated by tools/gen_theme_fonts.py from {t['regular']} and {t['light']}. Do not edit. */", '#include "bfont.h"', ""]
    total = 0
    for suffix, std, px in SIZES:
        codes, line_h, ascent = standard(std)
        s = 2 if px >= 96 else 1
        num = not std.startswith("ui")
        k = t["k_num"] if num else t["k_text"]
        ttf = os.path.join(ROOT, "tools", t["light"] if std.startswith("clock") else t["regular"])
        font = ImageFont.truetype(ttf, round(px * k / s))
        small = ImageFont.truetype(ttf, round(px * k * t["smallcaps"] / s)) if t["smallcaps"] else None
        name = t["prefix"] + suffix
        bits, glyphs = bytearray(), []
        for code in codes:
            ch, f = char_of(code), font
            if small and "a" <= ch <= "z": ch, f = ch.upper(), small
            f_asc = f.getmetrics()[0]
            adv = int(round(f.getlength(ch))) * s
            bbox = f.getbbox(ch, anchor="la")
            if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((code, adv, 0, 0, 0, 0, len(bits))); continue
            x0, y0, x1, y1 = bbox
            w, h = x1 - x0, y1 - y0
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor="la")
            p, off = img.load(), len(bits)
            for y in range(h):
                for x in range(0, w, 2):
                    a = (p[x, y] * 15 + 127) // 255
                    b = (p[x + 1, y] * 15 + 127) // 255 if x + 1 < w else 0
                    bits.append((a << 4) | b)
            glyphs.append((code, adv, w, h, x0 * s, ascent + (y0 - f_asc) * s, off))   # the baseline where the standard font has it
        out.append(f"static const uint8_t {name}_bits[{max(1, len(bits))}] = {{")
        out += ["  " + ",".join(f"0x{b:02x}" for b in bits[i:i + 24]) + "," for i in range(0, len(bits), 24)] or ["  0,"]
        out += ["};", "", f"static const bglyph_t {name}_glyphs[{len(glyphs)}] = {{"]
        out += [f"  {{ {c}, {a}, {w}, {h}, {xo}, {yo}, {o} }}," for c, a, w, h, xo, yo, o in glyphs]
        out += ["};", "", f"const bfont_t {name} = {{ {name}_glyphs, {len(glyphs)}, {line_h}, {ascent}, {name}_bits, {s} }};", ""]
        total += len(bits)
        print(f"{name}: {len(glyphs)} glyphs, {len(bits)} bytes, scale {s}")
    open(os.path.join(ROOT, "src", "fonts", theme + ".c"), "w").write("\n".join(out))
    print(f"{theme}.c: {total} bytes of glyphs")

for theme, t in THEMES.items():
    build(theme, t)
